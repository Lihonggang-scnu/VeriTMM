def _render_markdown(catalog: dict) -> str:
    lines = [
        "# Capability catalog (runtime-generated)",
        "",
        f"Generated at `{catalog['generated_at']}` by "
        "`py -3.11 -m tmm_engine.cli capability-catalog --regenerate`.  "
        "Do not edit by hand: CI compares this document against the live "
        "capability surface and fails on any drift.",
        "",
        "| capability | provider | operations | outputs | cost | verification |",
        "|---|---|---|---|---|---|",
    ]
    for record in catalog["capabilities"]:
        verification = record["verification"]
        verification_short = "/".join(
            name.replace("_", "-") for name, ok in verification.items() if ok
        )
        lines.append(
            "| `{id}` | {provider} | {operations} | {outputs} | {cost} | {verification} |".format(
                id=record["capability_id"],
                provider=record["provider"],
                operations=", ".join(record["operations"]),
                outputs=", ".join(record["outputs"][:4]) + ("…" if len(record["outputs"]) > 4 else ""),
                cost=record["estimated_cost_class"],
                verification=verification_short or "—",
            )
        )
    lines.append("")
    for record in catalog["capabilities"]:
        lines.append(f"## `{record['capability_id']}`")
        lines.append("")
        lines.append("```json")
        lines.append(json.dumps(record, indent=1, sort_keys=True, ensure_ascii=False))
        lines.append("```")
        lines.append("")
    return "\n".join(lines) + "\n"


_REGENERATE_HINT = (
    "run `py -3.11 -m tmm_engine.cli capability-catalog --regenerate` "
    "and commit the regenerated catalog"
)


def check_catalog(doc_path: str | Path = CATALOG_DOC, *, repo_root: Path | None = None) -> dict:
    """Drift gate: regenerate in memory and compare with the committed doc.

    Also enforces the staleness ordering: the catalog document must be newer
    than the newest capability-defining source file.  Returns a report with
    ``ok`` and a regeneration hint on failure.
    """

    root = Path(repo_root) if repo_root else Path(__file__).resolve().parents[1]
    doc = root / doc_path
    if not doc.is_file():
        return {"ok": False, "reason": "missing", "hint": _REGENERATE_HINT}
    catalog = build_catalog()
    expected_body = _render_markdown(catalog)
    actual = doc.read_text(encoding="utf-8")
    expected_no_stamp = _strip_stamp(expected_body)
    actual_no_stamp = _strip_stamp(actual)
    if actual_no_stamp != expected_no_stamp:
        diff_hint = _first_difference(actual_no_stamp, expected_no_stamp)
        return {
            "ok": False,
            "reason": "drift",
            "detail": diff_hint,
            "hint": _REGENERATE_HINT,
        }
    defining_sources = [
        root / "tmm_engine" / "capability_catalog.py",
        root / "tmm_engine" / "workbench.py",
        root / "tmm_engine" / "gradient_api.py",
        root / "tmm_engine" / "design_problem.py",
        root / "tmm_engine" / "job_runtime.py",
        root / "tmm_engine" / "intent" / "intent.py",
        root / "tmm_engine" / "protocol" / "capabilities.py",
    ]
    newest_source = max(
        (path.stat().st_mtime for path in defining_sources if path.is_file()),
        default=0.0,
    )
    if doc.stat().st_mtime < newest_source:
        return {
            "ok": False,
            "reason": "stale",
            "hint": _REGENERATE_HINT,
        }
    return {"ok": True}


def _strip_stamp(markdown: str) -> str:
    import re

    return re.sub(r"Generated at `[^`]+`", "Generated at `<stamp>`", markdown)


def _first_difference(actual: str, expected: str) -> str:
    actual_lines = actual.splitlines()
    expected_lines = expected.splitlines()
    for index, (a, e) in enumerate(zip(actual_lines, expected_lines)):
        if a != e:
            return f"line {index + 1}: doc={a!r} regenerated={e!r}"
    if len(actual_lines) != len(expected_lines):
        return (
            f"line count differs: doc={len(actual_lines)} "
            f"regenerated={len(expected_lines)}"
        )
    return "identical"


def write_catalog_doc(doc_path: str | Path = CATALOG_DOC) -> Path:
    path = Path(doc_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(_render_markdown(build_catalog()), encoding="utf-8")
    return path


