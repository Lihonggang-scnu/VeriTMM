"""Runtime-generated capability catalog with a drift gate.

The catalog is a *runtime self-attestation*: it is generated by walking the
real capability surface (backend registry, workbench, gradient/sensitivity
APIs, intent compiler, design-problem compiler, job runtime, benchmark) —
never by parsing documentation.  `check_catalog` re-generates in memory and
compares against the committed `docs/CAPABILITY_CATALOG.md`; any drift (a
hand-edited record, a new output, a changed schema) fails with the
regeneration hint.  A generation timestamp is stored but excluded from the
drift comparison.
"""

